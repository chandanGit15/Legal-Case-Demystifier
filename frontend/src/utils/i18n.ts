const STRINGS: Record<string, Dict> = { en: EN, hi: HI, kn: KN, ta: TA, te: TE, ml: ML, mr: MR, bn: BN };

/** Translate a chrome key for the given language; falls back to English. */
export function translate(lang: string, key: string, vars?: Record<string, string | number>): string {
  const dict = STRINGS[lang] ?? EN;
  let out = dict[key] ?? EN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.split(`{${k}}`).join(String(v));
    }
  }
  return out;
}
